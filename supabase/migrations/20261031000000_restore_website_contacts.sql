-- Restore the contact form's intended storage. Website visitors can submit,
-- but cannot read, update, or delete contact messages.
create table if not exists public.custom_contacts (
  id bigint generated by default as identity primary key,
  full_name text not null,
  email text not null,
  interested_division text,
  message text not null,
  created_at timestamptz not null default now()
);
alter table public.custom_contacts enable row level security;
revoke all on table public.custom_contacts from anon, authenticated;
grant insert (full_name, email, interested_division, message) on public.custom_contacts to anon, authenticated;
grant usage on sequence public.custom_contacts_id_seq to anon, authenticated;
drop policy if exists "Website contact submissions" on public.custom_contacts;
create policy "Website contact submissions" on public.custom_contacts
  for insert to anon, authenticated
  with check (
    char_length(btrim(full_name)) between 1 and 200
    and char_length(email) between 3 and 320
    and char_length(btrim(message)) between 1 and 10000
    and char_length(coalesce(interested_division, '')) <= 200
  );
notify pgrst, 'reload schema';
